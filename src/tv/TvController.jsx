
import React, { useEffect, useRef, useState } from 'react'
import { useLocation, useNavigate } from 'react-router-dom'
import { useTvMode, useTvModeActive } from './tvStore'
import './tv.css'

const pages = [
  ['Home', '/'],
  ['Search', '/search'],
  ['Library', '/library'],
  ['Settings', '/settings'],
]


const FOCUSABLE_SELECTOR = [
  'button:not(:disabled)',
  'a[href]',
  'input:not(:disabled)',
  'select:not(:disabled)',
  'textarea:not(:disabled)',
  '[tabindex="0"]',
  '[role="slider"]',
].join(', ')

const EDITABLE_SELECTOR = [
  'input',
  'textarea',
  'select',
  '[contenteditable]:not([contenteditable="false"])',
  '[role="slider"]',
  '[role="spinbutton"]',
].join(', ')

function editableElement(element) {
  return element?.closest?.(EDITABLE_SELECTOR) || null
}

function isVisible(element) {
  return element.getClientRects().length > 0
}

export default function TvController() {
  const mode = useTvMode()
  const active = useTvModeActive()
  const navigate = useNavigate()
  const location = useLocation()
  const [menuOpen, setMenuOpen] = useState(false)
  const [controllerConnected, setControllerConnected] = useState(false)
  const previousButtons = useRef({})
  const previousStickDirection = useRef({ x: null, y: null })
  const menuOpenRef = useRef(menuOpen)
  menuOpenRef.current = menuOpen

  useEffect(() => {
    if (!active) {
      setMenuOpen(false)
      return
    }

    function handleKeyDown(event) {
      const target = event.target instanceof Element ? event.target : document.activeElement
      const editingTarget = editableElement(target) || editableElement(document.activeElement)

      if (event.key === 'Escape') {
        const otherDialogOpen = [...document.querySelectorAll('[role="dialog"], [aria-modal="true"]')]
          .some(element =>
            isVisible(element) &&
            !element.closest('.lokal-tv-overlay')
          )
        if (editingTarget || otherDialogOpen) return

        setMenuOpen(value => !value)
        event.preventDefault()
        return
      }

      if (!event.key.startsWith('Arrow')) return
      // Preserve native caret movement, select navigation and slider adjustment for real key presses.
      // Synthetic arrow events generated by a gamepad remain available for TV focus navigation.
      if (event.isTrusted && editingTarget) return

      const overlay = menuOpenRef.current
        ? document.querySelector('.lokal-tv-overlay')
        : null
      const scope = menuOpenRef.current ? overlay : document
      if (!scope) return

      const elements = [...scope.querySelectorAll(FOCUSABLE_SELECTOR)].filter(isVisible)
      const current = document.activeElement

      if (!current || current === document.body || (menuOpenRef.current && !overlay.contains(current))) {
        event.preventDefault()
        elements[0]?.focus()
        return
      }

      const rect = current.getBoundingClientRect?.()
      if (!rect) return

      event.preventDefault()

      const cx = rect.left + rect.width / 2
      const cy = rect.top + rect.height / 2
      const candidates = elements
        .filter(element => element !== current)
        .map(element => {
          const targetRect = element.getBoundingClientRect()
          const dx = targetRect.left + targetRect.width / 2 - cx
          const dy = targetRect.top + targetRect.height / 2 - cy
          const forward =
            event.key === 'ArrowRight' ? dx > 0 :
            event.key === 'ArrowLeft' ? dx < 0 :
            event.key === 'ArrowDown' ? dy > 0 : dy < 0
          const distance = Math.hypot(dx, dy)
          const crossAxis =
            event.key === 'ArrowLeft' || event.key === 'ArrowRight'
              ? Math.abs(dy)
              : Math.abs(dx)
          return { element, score: forward ? distance + crossAxis * 1.5 : Infinity }
        })
        .sort((a, b) => a.score - b.score)

      candidates[0]?.element.focus()
    }

    window.addEventListener('keydown', handleKeyDown, true)

    let animationFrame
    let running = true

    function dispatchNavigationKey(key) {
      window.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true }))
    }

    function pollGamepads() {
      if (!running) return

      const pads = navigator.getGamepads?.() || []
      const pad = [...pads].find(gamepad => gamepad?.connected === true)

      if (pad) {
        setControllerConnected(true)
        const previous = previousButtons.current
        const pressed = index => !!pad.buttons[index]?.pressed && !previous[index]

        if (pressed(0)) {
          document.activeElement?.click?.()
        }

        if (pressed(1) || pressed(9)) {
          setMenuOpen(value => !value)
        }

        const axes = pad.axes || []
        const stickX =
          axes[0] < -0.7 ? 'ArrowLeft' :
          axes[0] > 0.7 ? 'ArrowRight' : null
        const stickY =
          axes[1] < -0.7 ? 'ArrowUp' :
          axes[1] > 0.7 ? 'ArrowDown' : null
        const previousStick = previousStickDirection.current

        const directions = [
          [pressed(14) || (stickX === 'ArrowLeft' && previousStick.x !== stickX), 'ArrowLeft'],
          [pressed(15) || (stickX === 'ArrowRight' && previousStick.x !== stickX), 'ArrowRight'],
          [pressed(12) || (stickY === 'ArrowUp' && previousStick.y !== stickY), 'ArrowUp'],
          [pressed(13) || (stickY === 'ArrowDown' && previousStick.y !== stickY), 'ArrowDown'],
        ]

        for (const [isPressed, key] of directions) {
          if (isPressed) dispatchNavigationKey(key)
        }

        previousStickDirection.current = { x: stickX, y: stickY }
        previousButtons.current = Object.fromEntries(
          pad.buttons.map((button, index) => [index, button.pressed])
        )
      } else {
        setControllerConnected(false)
        previousButtons.current = {}
        previousStickDirection.current = { x: null, y: null }
      }

      animationFrame = requestAnimationFrame(pollGamepads)
    }

    animationFrame = requestAnimationFrame(pollGamepads)

    return () => {
      running = false
      cancelAnimationFrame(animationFrame)
      window.removeEventListener('keydown', handleKeyDown, true)
    }
  }, [active])

  useEffect(() => {
    if (!active || !menuOpen) return
    const overlay = document.querySelector('.lokal-tv-overlay')
    const firstMenuButton = overlay?.querySelector('nav button') || overlay?.querySelector('button')
    firstMenuButton?.focus()
  }, [active, menuOpen])

  useEffect(() => {
    document.documentElement.classList.toggle('lokal-tv-mode', active)
    return () => document.documentElement.classList.remove('lokal-tv-mode')
  }, [active])

  // Automatic mode can enable controller-friendly navigation, but only an explicit
  // user choice should change the window's fullscreen state.
  useEffect(() => {
    const tv = window.electron?.tv
    if (!tv || mode !== 'on') return

    tv.setFullscreen(true).catch(error => {
      console.error('TV fullscreen toggle failed:', error)
    })

    return () => {
      tv.setFullscreen(false).catch(() => {})
    }
  }, [mode])

  if (!active) return null

  return (
    <>
      <div className="lokal-tv-status" aria-live="polite">
        TV MODE · {controllerConnected ? 'CONTROLLER CONNECTED' : 'READY'}
      </div>

      <button
        className="lokal-tv-menu-trigger"
        onClick={() => setMenuOpen(value => !value)}
        aria-label="Open TV navigation"
      >
        ☰
      </button>

      {menuOpen && (
        <div className="lokal-tv-overlay" role="dialog" aria-label="TV navigation">
          <div className="lokal-tv-panel">
            <div className="lokal-tv-panel-head">
              <strong>Lokal TV</strong>
              <button onClick={() => setMenuOpen(false)}>Close ✕</button>
            </div>

            <nav>
              {pages.map(([label, path]) => (
                <button
                  key={path}
                  className={location.pathname === path ? 'selected' : ''}
                  onClick={() => {
                    navigate(path)
                    setMenuOpen(false)
                  }}
                >
                  {label}
                </button>
              ))}
            </nav>

            <p>
              Use the D-pad or arrow keys to navigate. A or Enter selects.
              B or Escape opens and closes this menu.
            </p>
          </div>
        </div>
      )}
    </>
  )
}
